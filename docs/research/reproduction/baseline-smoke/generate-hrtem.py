"""Recreate the engineering-smoke periodic proxy in a NEW directory.

This is not a multislice HRTEM simulator. The committed TIFF is the exact input
used in the archived smoke; platform/libm differences may change regenerated
floating-point bytes. No STEM/defect image is generated by this script.
"""
from pathlib import Path
import argparse
import numpy as np
import tifffile
from PIL import Image

parser=argparse.ArgumentParser()
parser.add_argument('output',type=Path)
args=parser.parse_args()
args.output.mkdir(parents=True,exist_ok=False)
y,x=np.indices((128,128),dtype=np.float64)
a=np.cos(2*np.pi*(21*x+3*y)/128)+.6*np.cos(2*np.pi*(-4*x+17*y)/128+.3)
tifffile.imwrite(args.output/'source-A.tiff',a,metadata=None,photometric='minisblack')
Image.fromarray(np.rint((a-a.min())/(a.max()-a.min())*255).astype('uint8')).save(args.output/'source-A.png')
